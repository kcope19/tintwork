import { chromium } from 'playwright';
import path from 'node:path';
import { readFileSync } from 'node:fs';
const HERE = '/workspace/photo-editor';
const REAL = (f) => readFileSync(path.join(HERE, 'test-assets/real', f));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto('https://kcope19.github.io/tintwork/?platform=win&_=' + Date.now(), { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.tintwork); await page.evaluate(() => window.tintwork.engineReady);
await page.setInputFiles('#fileInput', { name: 'v117-cathedral.jpg', mimeType: 'image/jpeg', buffer: REAL('v117-cathedral.jpg') });
await page.waitForFunction(() => window.tintwork.doc?.name?.startsWith('v117-cathedral'));
await page.evaluate(async () => { await window.tintwork.idle(); await window.tintwork.compositeSettled?.(); });
await page.evaluate(() => window.tintwork.run('guidedUpright'));
await page.evaluate(() => window.tintwork.applySuggestedGuides(window.tintwork.mxf));
await page.waitForTimeout(400);
await page.screenshot({ path: path.join(HERE, 'screenshots/126-live-cathedral-suggest.png') });
const st = await page.evaluate(() => document.getElementById('status')?.textContent);
console.log(st);
await browser.close();
